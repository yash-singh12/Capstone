export function getGap(jobId) {
  if (GAP_BY_JOB[jobId]) return GAP_BY_JOB[jobId];
  const j = JOBS.find((x) => x.id === jobId);
  const matched = j.required.filter((s) => DEMO_STUDENT.skills.includes(s));
  const missing = j.required.filter((s) => !DEMO_STUDENT.skills.includes(s)).map((s) => ({ skill: s, importance: "Medium", reason: "Listed in JD" }));
  return { matchPercent: j.match, matched, missing, semanticNote: "Semantic vector match (mocked)." };
}
