export function getGap(jobId, skills = []) {
  const j = JOBS.find((x) => x.id === jobId);
  if (!j) return { matchPercent: 0, matched: [], missing: [], semanticNote: "No matching job found." };
  if (GAP_BY_JOB[jobId] && skills.length === 0) return GAP_BY_JOB[jobId];
  const matched = j.required.filter((s) => skills.includes(s));
  const missing = j.required
    .filter((s) => !skills.includes(s))
    .map((s) => {
      const known = GAP_BY_JOB[jobId]?.missing.find((item) => item.skill === s);
      return known || { skill: s, importance: "Medium", reason: "Listed in JD" };
    });
  const matchPercent = j.required.length
    ? Math.round((matched.length / j.required.length) * 100)
    : 0;
  return {
    matchPercent,
    matched,
    missing,
    semanticNote: "Matched against the skills in your active profile.",
  };
}
